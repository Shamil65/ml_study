# Подвиг 3. Уравнение разделяющей линии: w1 * x1 + w2 * x2 + w0 = 0
# Нужно по графику найти вектор w = [w0, w1, w2]^T.
#
# Решение (вручную):
#
# 1. Читаем с графика координаты двух отмеченных точек (клетка = 1):
#       A = (-3, 1)
#       B = ( 3, 5)
#
# 2. Обе точки лежат на линии, поэтому их координаты должны
#    удовлетворять уравнению w1 * x1 + w2 * x2 + w0 = 0:
#       A:  -3 * w1 + 1 * w2 + w0 = 0
#       B:   3 * w1 + 5 * w2 + w0 = 0
#
# 3. Вычитаем первое уравнение из второго (w0 сокращается):
#       6 * w1 + 4 * w2 = 0   =>   w1 = -(2/3) * w2
#
# 4. Три неизвестных, а уравнений два, потому что линию задаёт не один
#    вектор w, а целое семейство: если умножить w на любое число k != 0,
#    линия не изменится. Поэтому одну координату выбираем сами.
#    Берём w2 = -3 (чтобы все числа вышли целыми):
#       w1 = -(2/3) * (-3) = 2
#
# 5. Находим w0 из точки A:
#       -3 * 2 + 1 * (-3) + w0 = 0   =>   w0 = 9
#
# 6. Проверка по точке B:
#       3 * 2 + 5 * (-3) + 9 = 6 - 15 + 9 = 0  ✓
#
# Заодно сверяемся с графиком: линия x2 = (2/3) * x1 + 3 пересекает
# ось x2 в точке (0, 3), а ось x1 в точке (-4.5, 0), как и на рисунке.
#
# Ответ: w = [9, 2, -3]

w = [9, 2, -3]
