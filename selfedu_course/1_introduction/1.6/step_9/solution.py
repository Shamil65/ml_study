import numpy as np

# Подвиг 7. Разделяющая линия w1 * x1 + w2 * x2 + w0 = 0 и классификация точек.
# Ромбы - класс C1 = +1, квадраты - класс C2 = -1.
#
# Решение (вручную):
#
# 1. Читаем с графика координаты двух синих точек, через которые проходит
#    красная линия (клетка = 1):
#       A = (2, 0)
#       B = (7, 7)
#
# 2. Подставляем точки в уравнение линии:
#       A:  2 * w1 + 0 * w2 + w0 = 0   =>   w0 = -2 * w1
#       B:  7 * w1 + 7 * w2 + w0 = 0
#
# 3. Подставляем w0 из первого уравнения во второе:
#       7 * w1 + 7 * w2 - 2 * w1 = 0
#       5 * w1 + 7 * w2 = 0   =>   w1 = -(7 / 5) * w2
#
# 4. Три неизвестных, а уравнений два, поэтому масштаб вектора w выбираем
#    сами (умножение w на число k != 0 линию не меняет). Чтобы сократить
#    знаменатель 5, берём w2 = 5:
#       w1 = -(7 / 5) * 5 = -7
#       w0 = -2 * (-7) = 14
#
# 5. Проверка по точкам:
#       A:  -7 * 2 + 5 * 0 + 14 = -14 + 14 = 0          ✓
#       B:  -7 * 7 + 5 * 7 + 14 = -49 + 35 + 14 = 0     ✓
#
# 6. Проверяем знак. Ромбы (класс +1) должны давать w^T * x > 0.
#    Возьмём ромб (2, 4):
#       -7 * 2 + 5 * 4 + 14 = -14 + 20 + 14 = 20 > 0  ✓
#    Квадрат (9, 6) должен дать значение < 0:
#       -7 * 9 + 5 * 6 + 14 = -63 + 30 + 14 = -19 < 0  ✓
#    Знак выбран правильно, менять вектор на противоположный не нужно.
#    (Если бы ромбы дали отрицательные числа, весь вектор w пришлось бы
#    умножить на -1.)
#
# Ответ: w = [14, -7, 5]  (порядок: w0, w1, w2)
#
# Классификация: a(x) = sign(w^T * x), где x = [1, x1, x2].
# Дописываем к каждой точке единицу слева (для w0), получаем таблицу X
# размера (7, 3) и считаем X @ w сразу для всех точек: на выходе вектор
# из 7 чисел, берём от него знак.

x_test = [(9, 6), (2, 4), (-3, -1), (3, -2), (-3, 6), (7, -3), (6, 2)]

w = [14, -7, 5]

X = np.column_stack((np.ones(len(x_test)), x_test))
predict = np.sign(X @ w).astype(int).tolist()
