# Подвиг 5. Уравнение разделяющей линии: w1 * x1 + w2 * x2 + w0 = 0
# Нужно по графику найти вектор w = [w0, w1, w2]^T.
#
# Решение (вручную):
#
# 1. Читаем с графика координаты двух отмеченных точек (клетка = 1):
#       A = (-4, 0)
#       B = (-4, 6)
#    Линия вертикальная: у обеих точек одинаковая координата x1 = -4.
#
# 2. Обе точки лежат на линии, поэтому их координаты должны
#    удовлетворять уравнению w1 * x1 + w2 * x2 + w0 = 0:
#       A:  -4 * w1 + 0 * w2 + w0 = 0
#       B:  -4 * w1 + 6 * w2 + w0 = 0
#
# 3. Вычитаем первое уравнение из второго (-4 * w1 и w0 сокращаются):
#       6 * w2 = 0   =>   w2 = 0
#    Это логично: линия вертикальная, значит от x2 она не зависит.
#
# 4. Три неизвестных, а уравнений два, потому что линию задаёт не один
#    вектор w, а целое семейство: если умножить w на любое число k != 0,
#    линия не изменится. Поэтому одну координату выбираем сами.
#    Берём w1 = 1.
#
# 5. Находим w0 из точки A:
#       -4 * 1 + 0 * 0 + w0 = 0   =>   w0 = 4
#
# 6. Проверка:
#       A:  1 * (-4) + 0 * 0 + 4 = 0  ✓
#       B:  1 * (-4) + 0 * 6 + 4 = 0  ✓
#
# Уравнение линии: x1 + 4 = 0, то есть x1 = -4, как и на графике.
#
# Ответ: w = [4, 1, 0]

w = [4, 1, 0]
