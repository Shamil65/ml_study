# Подвиг 4. Уравнение разделяющей линии: w1 * x1 + w2 * x2 + w0 = 0
# Нужно по графику найти вектор w = [w0, w1, w2]^T.
#
# Решение (вручную):
#
# 1. Читаем с графика координаты двух отмеченных точек (клетка = 1):
#       A = (-3, 5)
#       B = ( 7, 5)
#    Линия горизонтальная: у обеих точек одинаковая координата x2 = 5.
#
# 2. Обе точки лежат на линии, поэтому их координаты должны
#    удовлетворять уравнению w1 * x1 + w2 * x2 + w0 = 0:
#       A:  -3 * w1 + 5 * w2 + w0 = 0
#       B:   7 * w1 + 5 * w2 + w0 = 0
#
# 3. Вычитаем первое уравнение из второго (5 * w2 и w0 сокращаются):
#       10 * w1 = 0   =>   w1 = 0
#    Это логично: линия горизонтальная, значит от x1 она не зависит.
#
# 4. Три неизвестных, а уравнений два, потому что линию задаёт не один
#    вектор w, а целое семейство: если умножить w на любое число k != 0,
#    линия не изменится. Поэтому одну координату выбираем сами.
#    Берём w2 = 1.
#
# 5. Находим w0 из точки A:
#       -3 * 0 + 5 * 1 + w0 = 0   =>   w0 = -5
#
# 6. Проверка:
#       A:  0 * (-3) + 1 * 5 - 5 = 0  ✓
#       B:  0 * 7    + 1 * 5 - 5 = 0  ✓
#
# Уравнение линии: x2 - 5 = 0, то есть x2 = 5, как и на графике.
#
# Ответ: w = [-5, 0, 1]

w = [-5, 0, 1]
