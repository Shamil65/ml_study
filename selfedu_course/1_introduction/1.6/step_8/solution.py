import numpy as np

# Подвиг 6. Разделяющая линия w1 * x1 + w2 * x2 + w0 = 0 и классификация точек.
# Квадраты - класс C1 = +1, ромбы - класс C2 = -1.
#
# Решение (вручную):
#
# 1. Читаем с графика координаты двух синих точек, через которые проходит
#    красная линия (клетка = 1):
#       A = (-5, 6)
#       B = ( 8, -3)
#
# 2. Подставляем точки в уравнение линии:
#       A:  -5 * w1 + 6 * w2 + w0 = 0
#       B:   8 * w1 - 3 * w2 + w0 = 0
#
# 3. Вычитаем второе уравнение из первого (w0 сокращается):
#       -13 * w1 + 9 * w2 = 0   =>   w1 = (9 / 13) * w2
#
# 4. Подставляем w1 в уравнение для точки A:
#       -5 * (9 / 13) * w2 + 6 * w2 + w0 = 0
#       (-45 / 13 + 78 / 13) * w2 + w0 = 0
#       (33 / 13) * w2 + w0 = 0   =>   w0 = -(33 / 13) * w2
#
# 5. Три неизвестных, а уравнений два, поэтому масштаб вектора w выбираем
#    сами (умножение w на число k != 0 линию не меняет). Чтобы сократить
#    знаменатель 13, берём w2 = 13:
#       w1 = (9 / 13) * 13 = 9
#       w0 = -(33 / 13) * 13 = -33
#
# 6. Проверка по точкам:
#       A:  9 * (-5) + 13 * 6 - 33 = -45 + 78 - 33 = 0  ✓
#       B:  9 * 8 + 13 * (-3) - 33 = 72 - 39 - 33 = 0   ✓
#
# 7. Проверяем знак. Квадраты (класс +1) должны давать w^T * x > 0.
#    Возьмём квадрат (-3, 8):
#       9 * (-3) + 13 * 8 - 33 = -27 + 104 - 33 = 44 > 0  ✓
#    Ромб (0, 0) должен дать значение < 0:
#       -33 < 0  ✓
#    Знак выбран правильно, менять вектор на противоположный не нужно.
#
# Ответ: w = [-33, 9, 13]  (порядок: w0, w1, w2)
#
# Классификация: a(x) = sign(w^T * x), где x = [1, x1, x2].
# Дописываем к каждой точке единицу слева (для w0), получаем таблицу X
# размера (7, 3) и считаем X @ w сразу для всех точек: на выходе вектор
# из 7 чисел, берём от него знак.

x_test = [(5, -3), (-3, 8), (3, 6), (0, 0), (5, 3), (-3, -1), (-3, 3)]

w = [-33, 9, 13]

X = np.column_stack((np.ones(len(x_test)), x_test))
predict = np.sign(X @ w).astype(int).tolist()
